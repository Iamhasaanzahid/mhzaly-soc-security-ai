try:
    from fpdf import FPDF
    FPDF_AVAILABLE = True
except ImportError:
    FPDF_AVAILABLE = False


if FPDF_AVAILABLE:
    class ExecutiveSecurityReport(FPDF):
        def header(self):
            self.set_font('helvetica', 'B', 14)
            self.set_text_color(224, 36, 36)
            self.cell(0, 10, 'MHZALY SOC & ENTERPRISE SECURITY PLATFORM', 0, 1, 'C')
            self.set_font('helvetica', 'I', 9)
            self.set_text_color(156, 163, 175)
            self.cell(0, 5, 'World-Class Executive Vulnerability & Threat Assessment Report', 0, 1, 'C')
            self.ln(8)

        def footer(self):
            self.set_y(-15)
            self.set_font('helvetica', 'I', 8)
            self.set_text_color(150, 150, 150)
            self.cell(0, 10, f'Page {self.page_no()} | Confidential — MHZALY Cyber Intelligence', 0, 0, 'C')


def generate_pdf_report(target: str, findings: List[Dict[str, Any]]) -> str:
    """Generates a professional PDF report containing scan findings and risk metrics."""
    if not FPDF_AVAILABLE:
        raise RuntimeError("fpdf2 is not installed.")

    pdf = ExecutiveSecurityReport()
    pdf.add_page()
    pdf.set_font('helvetica', '', 10)
    
    # Metadata Card
    pdf.set_font('helvetica', 'B', 11)
    pdf.cell(0, 7, f'Target Asset Scope: {target}', 0, 1)
    pdf.set_font('helvetica', '', 9)
    pdf.cell(0, 6, f'Assessment Timestamp: {datetime.utcnow().strftime("%Y-%m-%d %H:%M:%S UTC")} (Unified Intelligence Engine)', 0, 1)
    pdf.ln(5)
    
    # Findings Summary Table
    pdf.set_font('helvetica', 'B', 11)
    pdf.cell(0, 7, 'Threat Findings & Intelligence Matrix', 0, 1)
    pdf.set_font('helvetica', 'B', 9)
    pdf.set_fill_color(30, 41, 59)
    pdf.set_text_color(255, 255, 255)
    pdf.cell(30, 7, 'Severity', 1, 0, 'C', True)
    pdf.cell(120, 7, 'Vulnerability / Finding Description', 1, 0, 'L', True)
    pdf.cell(40, 7, 'Confidence', 1, 1, 'C', True)
    
    pdf.set_font('xx', '', 8) # Fallback or standard font
    pdf.set_font('helvetica', '', 8)
    pdf.set_text_color(0, 0, 0)
    if not findings:
        pdf.cell(190, 7, 'No vulnerabilities or active threats detected in current scope cycle.', 1, 1, 'C')
    else:
        for f in findings:
            sev = str(f.get('severity', 'INFO'))
            title = str(f.get('title', f.get('finding', 'Unknown')))[:65]
            conf = str(f.get('confidence', 'High'))
            pdf.cell(30, 6, sev, 1, 0, 'C')
            pdf.cell(120, 6, title, 1, 0, 'L')
            pdf.cell(40, 6, conf, 1, 1, 'C')
            
    tmp_file = tempfile.NamedTemporaryFile(delete=False, suffix='.pdf')
    pdf.output(tmp_file.name)
    return tmp_file.name
